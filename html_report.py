"""Generate a self-contained, escaped HTML report from Behavior Bench JSON artifacts."""
from __future__ import annotations

import html
import json
from pathlib import Path


def render_report(payload, output_path):
    cases = payload.get("cases", [])
    summary = payload.get("summary", payload)
    checked = [row for row in cases if row.get("expected_pass") is not None]
    pass_rate = None
    if checked:
        pass_rate = sum(bool(row.get("expected_pass")) for row in checked) / len(checked)
    forbidden_cases = sum(bool(row.get("forbidden_hits")) for row in cases)
    gate = summary.get("quality_gate", {})
    regression_rows = payload.get("regressions", [])
    title = html.escape(str(payload.get("model_id") or payload.get("candidate") or "Behavior Bench report"))
    esc = lambda value: html.escape("" if value is None else str(value))
    category_rows = []
    for category, metrics in summary.get("category_scores", {}).items():
        rate = metrics.get("expected_pass_rate")
        category_rows.append("<tr><td>" + html.escape(str(category)) + "</td><td>" + str(metrics.get("cases", 0)) +
            "</td><td>" + ("n/a" if rate is None else f"{rate:.1%}") + "</td><td>" +
            str(metrics.get("cases_with_forbidden_hits", 0)) + "</td><td>" +
            ("n/a" if metrics.get("mean_latency_ms") is None else str(metrics["mean_latency_ms"]) + " ms") + "</td></tr>")
    rows_html = []
    for row in cases:
        status = "No expected check"
        if row.get("expected_pass") is True:
            status = "PASS"
        elif row.get("expected_pass") is False:
            status = "FAIL"
        elif row.get("regression_detected"):
            status = "REGRESSION"
        hits = row.get("forbidden_hits", row.get("new_forbidden_hits", []))
        rows_html.append(
            "<tr><td>" + esc(row.get("id")) + "</td><td>" + esc(row.get("category", "uncategorized")) +
            "</td><td>" + esc(row.get("severity", "normal")) + "</td><td>" + esc(status) +
            "</td><td>" + esc(row.get("completion", row.get("candidate_completion", ""))[:1600]) +
            "</td><td>" + esc(", ".join(hits) if isinstance(hits, list) else hits) +
            "</td><td>" + esc(", ".join(row.get("regression_reasons", []))) + "</td></tr>"
        )
    pass_label = "n/a" if pass_rate is None else f"{pass_rate:.1%}"
    gate_label = "Not available" if "passed" not in gate else ("PASS" if gate["passed"] else "FAIL")
    html_doc = """<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>""" + title + """ — Behavior Bench</title>
<style>
:root{color-scheme:light dark;font-family:system-ui,-apple-system,sans-serif}
body{max-width:1200px;margin:2rem auto;padding:0 1rem;line-height:1.5}
h1{margin-bottom:.25rem}.muted{opacity:.72}.metrics{display:grid;grid-template-columns:repeat(auto-fit,minmax(150px,1fr));gap:.75rem;margin:1.5rem 0}
.metric{border:1px solid #8886;border-radius:12px;padding:1rem}.value{font-size:1.5rem;font-weight:700}
.table-wrap{overflow-x:auto}table{border-collapse:collapse;width:100%;min-width:750px}th,td{text-align:left;padding:.7rem;border-bottom:1px solid #8885;vertical-align:top}
td:nth-child(3){white-space:pre-wrap;overflow-wrap:anywhere;max-width:560px}
footer{margin-top:2rem;font-size:.9rem;opacity:.75}
</style></head><body>
<h1>Behavior Bench report</h1><p class="muted">""" + title + """</p>
<div class="metrics">
<div class="metric"><div class="muted">Cases</div><div class="value">""" + str(len(cases)) + """</div></div>
<div class="metric"><div class="muted">Expected-check pass rate</div><div class="value">""" + esc(pass_label) + """</div></div>
<div class="metric"><div class="muted">Cases with forbidden hits</div><div class="value">""" + str(forbidden_cases) + """</div></div>
<div class="metric"><div class="muted">Quality gate</div><div class="value">""" + esc(gate_label) + """</div></div>
<div class="metric"><div class="muted">Regressions</div><div class="value">""" + str(len(regression_rows)) + """</div></div>
</div>
<h2>Category scorecards</h2><div class="table-wrap"><table><thead><tr><th>Category</th><th>Cases</th><th>Expected pass rate</th><th>Forbidden-hit cases</th><th>Mean latency</th></tr></thead><tbody>""" + "".join(category_rows) + """</tbody></table></div>
<p class="muted">Substring checks are simple regression signals, not semantic evaluation or safety certification. Review completions in context.</p>
<h2>Case results</h2><div class="table-wrap"><table><thead><tr><th>Case</th><th>Category</th><th>Severity</th><th>Expected check</th><th>Completion (truncated)</th><th>Forbidden hits</th><th>Regression reasons</th></tr></thead>
<tbody>""" + "".join(rows_html) + """</tbody></table></div>
<footer>Generated by Behavior Bench. Treat prompt and completion contents as potentially sensitive; share this file only with authorized reviewers.</footer>
</body></html>"""
    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(html_doc, encoding="utf-8")
    return str(path)
